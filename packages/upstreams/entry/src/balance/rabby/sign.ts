/// <reference path="./vendor.d.ts" />

import { Effect } from "effect";
import { SigningFailure, summaryOf } from "../../runtime/errors";
import { RABBY_CLIENT, RABBY_CLIENT_VERSION } from "./constants";
import RABBY_WASM from "./vendor/rabby_sign.wasm";
import type { RabbySignature } from "./vendor/sign-patched.cjs";

// Rabby request signing. Unsigned is not a 401 but a rate tier: measured on one IP and endpoint, signed 20 in a row all pass, unsigned gets
// a 429 after 2 requests with no Retry-After and still 429 after 45s. So signing is required, not an optimisation.
// How wasm enters the Worker (do not change this into importing the upstream package directly): Workers forbid runtime wasm compilation
// (`Wasm code generation disallowed by embedder`, sync and async), while the upstream bundle does `new WebAssembly.Module(inline base64)` at module
// evaluation whenever there is no window, which is exactly a Worker's shape. So vendor it: the wasm is extracted to a .wasm file compiled at build
// time and the compiled Module is handed to the patched bundle via `globalThis.__RABBY_WASM__`. The patch is generated by vendor/regenerate.mjs; do not hand-edit.

// Global key for handing over the compiled Module; must be set before importing the patched bundle, which uses it at module evaluation.
const WASM_HANDOFF_KEY = "__RABBY_WASM__";

// Host fingerprint: in the browser extension it is chrome-extension://<extension id>/bridge.html. It enters the signature computation so it must be
// passed, but upstream does not validate its content today (a random id works: signatures computed in workerd got 20/20 200s from rabby).
// If upstream starts validating, this is the first thing to break.
// `Math.random()` rather than Effect's `Random`: it is not business randomness, needs no reproducibility, and is called only once at wasm init.
const hostFingerprint = (): string =>
  `chrome-extension://${Math.random().toString(36).slice(2)}/bridge.html`;

type Signer = {
  cattleGsW(params: Record<string, unknown>, method: string, path: string): RabbySignature;
};

// Lazy and loaded once (isolate-level). Do not hoist to module top level: a Worker has a startup CPU budget and wasm instantiation must stay off the startup path.
let signerPromise: Promise<Signer> | null = null;

type LoadedSigner = Signer & { lW?: (hf?: string) => Promise<unknown> };

const usable = (v: unknown): v is Required<LoadedSigner> =>
  typeof (v as LoadedSigner)?.lW === "function" &&
  typeof (v as LoadedSigner)?.cattleGsW === "function";

async function loadSigner(): Promise<Signer> {
  const globals = globalThis as unknown as Record<string, unknown>;
  globals[WASM_HANDOFF_KEY] = RABBY_WASM;
  const mod = await import("./vendor/sign-patched.cjs");
  // The upstream file is UMD; which shape it lands in depends on the bundler: CJS interop gives `default`; evaluated as ESM,
  // `module`/`exports`/`define` are all undefined so it takes the last branch and attaches to `self.RabbySign`. All three are accepted;
  // the `.cjs` filename aims for the first, the other two are a safety net.
  const signer = [
    (mod as { default?: unknown }).default,
    mod,
    (globals as { RabbySign?: unknown }).RabbySign,
  ].find(usable);
  if (!signer) {
    throw new Error("rabby-sign: vendored bundle is missing lW/cattleGsW");
  }
  await signer.lW(hostFingerprint());
  return signer;
}

function signer(): Promise<Signer> {
  // A failure is not cached: one failed load must not leave this isolate unable to sign forever.
  signerPromise ??= loadSigner().catch((err) => {
    signerPromise = null;
    throw err;
  });
  return signerPromise;
}

// Signing header. `params` must equal the query actually sent (it is what is signed; upstream hashes it sorted by key).
// Failures are `SigningFailure`, not transport faults: not being able to sign usually means upstream changed the signing protocol (re-vendor), so retrying is a wasted round trip.
export function signRabbyRequest(
  method: string,
  path: string,
  params: Record<string, unknown>,
): Effect.Effect<Record<string, string>, SigningFailure> {
  return Effect.tryPromise({
    try: async () => {
      const { ts, nonce, version, signature } = (await signer()).cattleGsW(params, method, path);
      return {
        "X-Api-Ts": encodeURIComponent(String(ts)),
        "X-Api-Nonce": encodeURIComponent(nonce),
        "X-Api-Ver": encodeURIComponent(version),
        "X-Api-Sign": encodeURIComponent(signature),
        "X-Client": RABBY_CLIENT,
        "X-Version": RABBY_CLIENT_VERSION,
      };
    },
    catch: (cause) => new SigningFailure({ where: path, cause: summaryOf(cause) }),
  });
}

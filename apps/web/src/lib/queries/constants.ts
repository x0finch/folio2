// 各域 queryOptions 的 `staleTime` 分档。
//
// **绝不设成 QueryClient 的全局默认**(ADR 0038)。全局默认会一次性打断所有**还没迁**的域:
// 它们仍靠整页 `router.invalidate()` 刷新,而那条路只在数据 stale 时才真拉 —— 一旦全局
// staleTime > 0,它们就静默失效(loader 照常重跑,不报错,只表现为「改了东西画面不变」)。
// 设在各自的 queryOptions 上,才能一个域一个域地开:某域的档位只在**它的写路径也迁完**
// 的那一片才打开。
//
// 分档按「这份数据多久会自己变」来定,不按页面。新域迁进来时往这里加一档,别就地写数字。
export const STALE_TIME = {
  // 余额、同步状态一类:一轮同步会改它,但不会在几十秒内自己变。
  // 够覆盖「首页 ⇄ 账户页来回切」和 hover 预热,又短到用户回头看时不至于是旧的。
  live: 30_000,
} as const;
